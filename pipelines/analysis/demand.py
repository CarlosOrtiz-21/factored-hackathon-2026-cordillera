"""Demand analysis: the data-backed case (and its limits) for the card-support workflow.

Reads the gold/silver tables built by the ETL and writes docs/DEMAND_ANALYSIS.md plus
a CSV with the monthly card-complaint series for the slides.

Usage:
    uv run python -m pipelines.analysis.demand
"""

from pathlib import Path

import duckdb

from cardagent.config import get_settings

REPORT = Path("docs/DEMAND_ANALYSIS.md")
MONTHLY_CSV = Path("docs/data/card_complaints_monthly.csv")
CARD_TYPES = "('Tarjeta Crédito', 'Tarjeta Débito')"


def md_table(con, sql: str) -> list[str]:
    result = con.execute(sql)
    cols = [d[0] for d in result.description]
    rows = result.fetchall()
    fmt = lambda v: f"{v:,}" if isinstance(v, int) else str(v)  # noqa: E731
    return [
        "| " + " | ".join(cols) + " |",
        "|" + "---|" * len(cols),
        *("| " + " | ".join(fmt(v) for v in r) + " |" for r in rows),
    ]


def build_report(con) -> list[str]:
    footprint = md_table(
        con,
        f"""
        SELECT 'Products' AS metric,
               count(*) FILTER (WHERE product_type IN {CARD_TYPES}) AS cards,
               count(*) AS total,
               round(100 * cards / total, 1) AS card_share_pct
        FROM silver_products
        UNION ALL
        SELECT 'Transactions',
               (SELECT count(*) FROM gold_card_transactions), count(*),
               round(100 * (SELECT count(*) FROM gold_card_transactions) / count(*), 1)
        FROM silver_transactions
        UNION ALL
        SELECT 'Complaints with a linked product',
               count(*) FILTER (WHERE affects_card), count(affected_product_id),
               round(100 * count(*) FILTER (WHERE affects_card) / count(affected_product_id), 1)
        FROM gold_complaints
    """,
    )
    card_complaints = md_table(
        con,
        """
        SELECT coalesce(subcategory, '(missing)') AS subcategory,
               count(*) AS complaints,
               round(100 * avg(sla_breached::INT), 1) AS sla_breach_pct,
               median(resolution_days) AS median_resolution_days,
               round(100 * avg((status = 'Escalated')::INT), 1) AS escalated_pct
        FROM gold_complaints WHERE affects_card
        GROUP BY 1 ORDER BY complaints DESC
    """,
    )
    card_status = md_table(
        con,
        """
        SELECT card_kind, product_status, count(*) AS cards,
               round(100 * count(*) / sum(count(*)) OVER (PARTITION BY card_kind), 1) AS pct
        FROM gold_card_products GROUP BY card_kind, product_status ORDER BY card_kind, cards DESC
    """,
    )
    contact_baseline = md_table(
        con,
        """
        SELECT reason_category, count(*) AS contacts,
               round(100 * avg(was_resolved::INT), 1) AS fcr_pct,
               round(100 * avg(was_escalated::INT), 1) AS escalated_pct,
               median(duration_seconds) AS median_handle_s,
               median(wait_time_seconds) AS median_wait_s
        FROM silver_call_center_interactions GROUP BY 1 ORDER BY contacts DESC
    """,
    )
    fraud = md_table(
        con,
        """
        SELECT card_kind, count(*) AS transactions,
               count(*) FILTER (WHERE is_fraud) AS fraud,
               round(100 * avg(is_fraud::INT), 3) AS fraud_pct
        FROM gold_card_transactions GROUP BY 1
    """,
    )
    mentions = con.execute("""
        WITH m AS (
            SELECT customer_id, trim(unnest(string_split(mentioned_products, ','))) AS pid
            FROM silver_call_center_interactions WHERE mentioned_products IS NOT NULL
        )
        SELECT count(*), count(p.product_id) FROM m
        LEFT JOIN silver_products p ON p.product_id = m.pid
    """).fetchone()

    return [
        "# Demand analysis: card support",
        "",
        "Offline analysis of the synthetic LATAM Bank dataset (v1.0.0), generated by "
        "`pipelines/analysis/demand.py` from the ETL warehouse. These are dataset facts, "
        "not production measurements.",
        "",
        "## 1. Cards are about a third of the bank's footprint",
        *footprint,
        "",
        "## 2. Card complaints: where the service pain is",
        'Complaints whose `affected_product_id` is a card. "Cargo no reconocido" '
        "(unrecognized charge) is the case the assistant **escalates with a structured "
        "handoff** instead of resolving.",
        "",
        *card_complaints,
        "",
        "## 3. Card status mix: what the assistant will look up and change",
        *card_status,
        "",
        "## 4. Contact-center baseline (all reasons)",
        "The operational baseline the assistant is measured against: first-contact "
        "resolution (FCR), escalation rate, and handle and wait times per contact category.",
        "",
        *contact_baseline,
        "",
        "## 5. Fraud on card transactions (label used by the learned fraud model, step 1c)",
        *fraud,
        "",
        "## Limitations (stated honestly)",
        f"- **Call-center contacts can't be attributed to cards.** Of {mentions[0]:,} product "
        f"mentions in `call_center_interactions.mentioned_products`, only {mentions[1]:,} "
        f"({100 * mentions[1] / mentions[0]:.2f}%) exist in `products`, and none belong to the "
        "interaction's customer. The link is broken in the source, so card demand is measured "
        "through complaints, products, and transactions instead.",
        "- `contact_reason` has only 6 coarse categories (identical to `reason_category`), and "
        "transcripts are 42 templates, so they can't label card intents.",
        "- The synthetic distributions are close to uniform (e.g. card and non-card complaints "
        "have similar SLA-breach rates). The data supports cards as a **large, representative** "
        "workload, not as an unusually painful one. The workflow choice also rests on it being "
        "the best fit for a safe read + single-write (block) automation with human approval.",
        "",
    ]


def monthly_series(con, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    con.execute(f"""
        COPY (
            SELECT date_trunc('month', creation_date)::DATE AS month,
                   count(*) FILTER (WHERE affects_card) AS card_complaints,
                   count(*) FILTER (WHERE affects_card AND subcategory = 'Cargo no reconocido')
                       AS card_unrecognized_charges,
                   count(*) AS all_complaints
            FROM gold_complaints GROUP BY 1 ORDER BY 1
        ) TO '{dest.as_posix()}' (HEADER)
    """)


def main() -> None:
    con = duckdb.connect(str(get_settings().warehouse_path), read_only=True)
    REPORT.write_text("\n".join(build_report(con)), encoding="utf-8")
    monthly_series(con, MONTHLY_CSV)
    print(f"wrote {REPORT} and {MONTHLY_CSV}")


if __name__ == "__main__":
    main()
